package Modelo;

public class Avances {
    int id;
    String modulo;
    String porcentaje;

    public Avances() {
    }
  
    public Avances(int id, String modulo, String porcentaje) {
        this.id = id;
        this.modulo = modulo;
        this.porcentaje = porcentaje;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getModulo() {
        return modulo;
    }

    public void setModulo(String modulo) {
        this.modulo = modulo;
    }

    public String getPorcentaje() {
        return porcentaje;
    }

    public void setPorcentaje(String porcentaje) {
        this.porcentaje = porcentaje;
    }
}
